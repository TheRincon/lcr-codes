//! AWGN decoding thresholds for the §8.2 rate family — §14.5 step 5.
//!
//! `cargo run -p xtask -- thresholds > docs/ldpc.md`
//!
//! §14.5 is explicit that the code should be "validated standalone over AWGN with a
//! BER-vs-SNR curve checked against theory, **before** wiring into the symbol path", and
//! `ldpc.rs` already refers to "absolute thresholds recorded in docs/ldpc.md" — a file
//! that did not exist. This produces it.
//!
//! ## Why this has to come before tuning rates from the symbol path
//!
//! Sweeping impairments on a rendered symbol does not isolate the code. Past a certain
//! magnitude the finder scan stops locating the symbol at all, and every rate fails
//! together at that point because nothing reaches the decoder — the `tune` example shows
//! exactly this, with the noise threshold pinned at the same magnitude for three
//! different ECC levels. A rate table fitted to that data would be fitting the detector.
//!
//! Measured here instead: the SNR each rate needs on a clean AWGN channel. That is the
//! code's own property, independent of optics, and it is what the per-layer channel
//! quality has to be compared against.

use lcr_core::ecc::ldpc::{Code, MAX_ITERATIONS, RATES};
use std::fmt::Write as _;

/// Trials per SNR point. Frame error rate is a binomial proportion, so the standard
/// error near FER = 0.5 is `0.5/√n` — 240 gives about ±3 points, enough to place a
/// crossing to a tenth of a dB against a waterfall this steep.
const TRIALS: usize = 240;
/// SNR grid, dB.
const SNR_LO: f32 = 0.0;
const SNR_HI: f32 = 8.0;
const SNR_STEP: f32 = 0.5;

/// Representative layer lengths: a v1 chroma layer, a mid-sized one, and a v32 luma layer.
const LENGTHS: [(usize, &str); 3] = [(162, "short"), (2014, "mid"), (19406, "long")];

struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }
    fn unit(&mut self) -> f32 {
        (self.next() >> 11) as f32 / (1u64 << 53) as f32
    }
    fn bit(&mut self) -> bool {
        self.next() & 1 == 1
    }
    fn normal(&mut self) -> f32 {
        let u1 = self.unit().max(1e-9);
        (-2.0 * u1.ln()).sqrt() * (std::f32::consts::TAU * self.unit()).cos()
    }
}

/// Frame error rate for one rate index at one SNR.
///
/// BPSK over AWGN: a bit is sent as ±1 and received with Gaussian noise of standard
/// deviation `sigma`, giving the exact LLR `2y/sigma²` that §12.4 approximates from
/// colour. `snr_db` is `1/sigma²` in dB, i.e. per-symbol SNR, not `Eb/N0` — the two
/// differ by the code rate, and per-symbol is the one comparable across rates here
/// because every layer gets the same number of *channel uses*, not the same energy
/// per information bit.
fn frame_error_rate(rate: usize, n: usize, snr_db: f32, seed: u64) -> f32 {
    let Ok(code) = Code::new(rate, n) else {
        return f32::NAN;
    };
    let sigma = (10f32.powf(-snr_db / 10.0)).sqrt();
    let mut rng = Rng(seed | 1);
    let mut errors = 0usize;
    for _ in 0..TRIALS {
        let info: Vec<bool> = (0..code.info_bits()).map(|_| rng.bit()).collect();
        let tx = code.encode(&info).unwrap();
        let llrs: Vec<f32> = tx
            .iter()
            .map(|&b| {
                let s = if b { -1.0 } else { 1.0 };
                let y = s + sigma * rng.normal();
                2.0 * y / (sigma * sigma)
            })
            .collect();
        if code.decode(&llrs, MAX_ITERATIONS).unwrap().bits != info {
            errors += 1;
        }
    }
    errors as f32 / TRIALS as f32
}

/// SNR at which the frame error rate crosses `target`, interpolated on the grid.
fn crossing(curve: &[(f32, f32)], target: f32) -> Option<f32> {
    for w in curve.windows(2) {
        let ((s0, f0), (s1, f1)) = (w[0], w[1]);
        if f0 >= target && f1 < target {
            let t = (f0 - target) / (f0 - f1).max(1e-6);
            return Some(s0 + t * (s1 - s0));
        }
    }
    None
}

pub fn report() -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "# LDPC decoding thresholds\n\n\
         Generated by `cargo run -p xtask -- thresholds`. §14.5 step 5.\n\n\
         Frame error rate over BPSK/AWGN, {TRIALS} frames per point, min-sum with the \
         shipped base graphs.\n`SNR` is per channel symbol (`1/σ²`), not `Eb/N0`: every \
         layer gets the same number of\nchannel uses regardless of rate, so per-symbol is \
         the comparable axis.\n\n\
         `FER 50%` is the waterfall midpoint; `FER 5%` is closer to an operating point.\n"
    );

    for (n, label) in LENGTHS {
        let _ = writeln!(s, "\n## {label} layer — n = {n}\n");
        let _ = writeln!(s, "| rate | FER 50% | FER 5% | vs. 0.85 |");
        let _ = writeln!(s, "|---:|---:|---:|---:|");
        let mut base = None;
        for (i, &rate) in RATES.iter().enumerate() {
            let mut curve = Vec::new();
            let mut snr = SNR_LO;
            while snr <= SNR_HI {
                curve.push((snr, frame_error_rate(i, n, snr, 0x51ED + i as u64 * 977)));
                snr += SNR_STEP;
            }
            let f50 = crossing(&curve, 0.5);
            let f05 = crossing(&curve, 0.05);
            if i == 0 {
                base = f50;
            }
            let gain = match (f50, base) {
                (Some(a), Some(b)) => format!("{:+.1} dB", a - b),
                _ => "—".into(),
            };
            let fmt = |v: Option<f32>| v.map_or("—".into(), |x| format!("{x:.2} dB"));
            let _ = writeln!(s, "| {rate:.2} | {} | {} | {gain} |", fmt(f50), fmt(f05));
        }
    }

    // ---- what the §8.2 pairing actually assumes ---------------------------------
    let _ = writeln!(
        s,
        "\n## What §8.2's unequal protection assumes\n\n\
         §8.2 pairs each ECC level's luma rate with a chroma rate two steps stronger, and \
         calls the\ninequality load-bearing: chroma is \"measured over a noisier, \
         lower-bandwidth channel\".\nThat pairing is a quantitative claim — the extra \
         protection is worth a specific number of dB,\nand it is only the right amount if \
         the chroma channel is worse by that same amount:\n"
    );
    let _ = writeln!(s, "| level | luma rate | chroma rate | chroma margin |");
    let _ = writeln!(s, "|---:|---:|---:|---:|");
    let n = 2014;
    let mut curves = Vec::new();
    for i in 0..RATES.len() {
        let mut curve = Vec::new();
        let mut snr = SNR_LO;
        while snr <= SNR_HI {
            curve.push((snr, frame_error_rate(i, n, snr, 0x9001 + i as u64 * 131)));
            snr += SNR_STEP;
        }
        curves.push(crossing(&curve, 0.5));
    }
    for level in 0..4usize {
        let (li, ci) = (
            lcr_core::ecc::ldpc::LUMA_RATE_INDEX[level],
            lcr_core::ecc::ldpc::CHROMA_RATE_INDEX[level],
        );
        let margin = match (curves[li], curves[ci]) {
            (Some(l), Some(c)) => format!("{:.1} dB", l - c),
            _ => "—".into(),
        };
        let _ = writeln!(
            s,
            "| {level} | {:.2} | {:.2} | {margin} |",
            RATES[li], RATES[ci]
        );
    }
    let _ = writeln!(
        s,
        "\nSo the table as pinned assumes the chroma channel runs that many dB below luma. \
         Confirming\nor correcting it needs a measured chroma-channel SNR from the symbol \
         path, which the decoder\ndoes not yet report — `Diagnostics::estimated_snr_db` is \
         luma only. That measurement is the\nremaining work on open decision #5; the \
         thresholds above are the half that can be settled\nwithout optics."
    );
    s
}
